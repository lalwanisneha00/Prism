// Writes src/data/subjects/index.generated.ts: one import per subject file (and per
// "<id>-sources.json" file) in src/data/subjects/. Adding a subject is then just adding a
// JSON file, no code change (SPEC §12.1 rule 3). Runs before dev, build and tests; a test
// also fails if the committed index doesn't match the folder.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = "src/data/subjects";
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort();
const subjects = files.filter((f) => !f.endsWith("-sources.json"));
const sources = files.filter((f) => f.endsWith("-sources.json"));
const name = (f, suffix) =>
  `${f.replace(/-sources\.json$|\.json$/, "").replace(/[^a-z0-9]+(.)/gi, (_, c) => c.toUpperCase())}${suffix}`;

const lines = [
  "// Generated by scripts/build-subject-index.mjs from the files in this folder. Do not edit.",
  ...subjects.map((f) => `import ${name(f, "Subject")} from "./${f}";`),
  ...sources.map((f) => `import ${name(f, "Sources")} from "./${f}";`),
  "",
  "/** Every subject file, in file-name order. */",
  `export const subjectFiles: unknown[] = [${subjects.map((f) => name(f, "Subject")).join(", ")}];`,
  "",
  "/** Grounding sources per subject id (from <id>-sources.json). */",
  "export const sourceFiles: Record<string, unknown> = {",
  ...sources.map((f) => `  "${f.replace(/-sources\.json$/, "")}": ${name(f, "Sources")},`),
  "};",
  "",
];
const out = `${dir}/index.generated.ts`;
const next = lines.join("\n");
let current = "";
try {
  current = readFileSync(out, "utf8");
} catch {
  // first run
}
if (current !== next) writeFileSync(out, next);
