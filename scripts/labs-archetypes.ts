/*
 * Lab archetype report (syllabus fix, Phase 7C): every lab course with the lesson format it gets,
 * experiments moved to another format, and anything worth a human look. Writes
 * handouts/_parsed/LAB_ARCHETYPES.md and docs/LAB_ARCHETYPE_GAPS.md. Run: npm run labs:archetypes
 * (after editing src/data/labs/archetypes.json).
 */
import { writeFileSync } from "node:fs";
import { ARCHETYPES, classifyCourse, classifyExperiment } from "@/lib/labs/archetypes";
import { experimentsOf } from "@/lib/labs/experiment";
import { labSubjects } from "@/lib/subjects";

const HOW: Record<string, string> = {
  override: "set by hand (overrides)",
  name: "course name",
  experiments: "guessed from the experiment names",
  branch: "guessed from the branch",
  generic: "no archetype fits",
};

type Row = {
  id: string;
  name: string;
  branches: string;
  archetype: string;
  letter: string;
  how: string;
  experiments: number;
  moved: { name: string; to: string }[];
  notes: string[];
};

const rows: Row[] = labSubjects
  .map((lab) => {
    const c = classifyCourse(lab);
    const exps = experimentsOf(lab);
    const moved = exps
      .map(({ topic }) => ({ topic, e: classifyExperiment(lab, topic) }))
      .filter(({ e }) => e.archetype.id !== c.archetype.id)
      .map(({ topic, e }) => ({
        name: topic.name,
        to: `${e.archetype.letter} ${e.archetype.name}`,
      }));
    const notes: string[] = [];
    if (c.how !== "name" && c.how !== "override") notes.push(HOW[c.how]);
    if (exps.length === 0) notes.push("no experiments listed in the handout");
    if (moved.length)
      notes.push(`${moved.length} of ${exps.length} experiments use another format`);
    return {
      id: lab.id,
      name: lab.name,
      branches: (lab.branches ?? []).join(", "),
      archetype: c.archetype.name,
      letter: c.archetype.letter,
      how: HOW[c.how],
      experiments: exps.length,
      moved,
      notes,
    };
  })
  .sort((a, b) => a.letter.localeCompare(b.letter) || a.name.localeCompare(b.name));

const all = [...ARCHETYPES.archetypes, ARCHETYPES.generic];
const count = (letter: string) => rows.filter((r) => r.letter === letter).length;
const uncertain = rows.filter((r) => r.notes.length > 0);

const md = [
  "# Lab archetypes",
  "",
  "Which lesson format each lab course gets (syllabus fix, Phase 7C). Generated by `npm run labs:archetypes` from `src/data/labs/archetypes.json`; to change a lab, add it to `overrides.courses` there (or `overrides.experiments` for one experiment, key `subject/topic`) and run the script again.",
  "",
  `${rows.length} lab courses. ` +
    all.map((a) => `${a.letter} ${a.name}: ${count(a.letter)}`).join("; ") +
    ".",
  "",
  "## Worth a check",
  "",
  ...(uncertain.length
    ? uncertain.map(
        (r) =>
          `- **${r.name}** (${r.branches}): ${r.letter} ${r.archetype}. ${r.notes.join("; ")}.`,
      )
    : ["Nothing."]),
  "",
  ...all.flatMap((a) => {
    const list = rows.filter((r) => r.letter === a.letter);
    if (!list.length) return [];
    return [
      `## ${a.letter}. ${a.name} (${list.length})`,
      "",
      "| Lab | Branches | Experiments | Decided by | Notes |",
      "| --- | --- | --- | --- | --- |",
      ...list.map(
        (r) =>
          `| ${r.name} (\`${r.id}\`) | ${r.branches} | ${r.experiments} | ${r.how} | ${r.moved.length ? r.moved.map((m) => `${m.name.replace(/\|/g, "/").slice(0, 70)} → ${m.to}`).join("<br>") : ""} |`,
      ),
      "",
    ];
  }),
];
writeFileSync("handouts/_parsed/LAB_ARCHETYPES.md", md.join("\n"));

const gaps = rows.filter((r) => r.letter === ARCHETYPES.generic.letter);
const gapMd = [
  "# Lab archetype gaps",
  "",
  "Lab courses no archetype fits yet (syllabus fix, Phase 7C). Their lessons use the general format (aim, theory, apparatus, procedure, observations, result, viva). Ideas for the next archetypes. Generated by `npm run labs:archetypes`.",
  "",
  ...(gaps.length
    ? gaps.map((r) => `- ${r.name} (${r.branches}), ${r.experiments} experiments`)
    : ["None."]),
  "",
];
writeFileSync("docs/LAB_ARCHETYPE_GAPS.md", gapMd.join("\n"));
console.log(
  `${rows.length} labs; ${uncertain.length} worth a check; ${gaps.length} with no archetype. Wrote handouts/_parsed/LAB_ARCHETYPES.md and docs/LAB_ARCHETYPE_GAPS.md`,
);
